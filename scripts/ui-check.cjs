async (page) => {
  const checks = [];
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
  const recovery = async () => {
    await delay(950);
    return page.evaluate(() => new Promise((resolve, reject) => {
      const req = indexedDB.open('agentsketch', 1);
      req.onsuccess = () => { const db = req.result, read = db.transaction('documents').objectStore('documents').get('recovery'); read.onsuccess = () => { resolve(JSON.parse(read.result)); db.close(); }; read.onerror = reject; };
      req.onerror = reject;
    }));
  };
  const press = async key => { await page.locator('#board').focus(); await page.keyboard.press(key); };
  const drag = async (x1,y1,x2,y2) => { await page.mouse.move(x1,y1); await page.mouse.down(); await page.mouse.move(x2,y2,{steps:12}); await page.mouse.up(); };
  await page.setViewportSize({ width: 1440, height: 900 });
  if (await page.locator('.confirm-dialog').isVisible()) await page.getByRole('button',{name:'취소',exact:true}).click();
  await page.screenshot({ path: 'output/playwright/desktop.png' });
  await page.setViewportSize({ width: 960, height: 640 });
  await page.screenshot({ path: 'output/playwright/compact.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '960px layout fits without horizontal overflow');
  await page.setViewportSize({ width: 1440, height: 900 });
  await press('Control+n');
  if (await page.locator('.confirm-dialog').isVisible()) await page.getByRole('button',{name:'저장하지 않고 계속'}).click();
  await page.locator('[data-tool="rect"]').click();
  await drag(220,230,430,340);
  await page.mouse.dblclick(320,280);
  await page.locator('#text-editor').fill('첫 번째 조건\nERP 자료 확인');
  await page.locator('#text-editor').press('Control+Enter');
  let doc = await recovery();
  assert(doc.nodes.length === 1 && doc.nodes[0].text.includes('ERP'), 'rectangle creation and multiline Korean text editing');
  const first = doc.nodes[0].id;
  await page.locator('[data-tool="round"]').click();
  await drag(640,390,860,510);
  await page.mouse.dblclick(740,440);
  await page.locator('#text-editor').fill('월간보고 준비');
  await page.locator('#text-editor').press('Control+Enter');
  await page.locator('[data-tool="connect"]').click();
  await page.mouse.click(320,280); await page.mouse.click(740,440);
  await page.locator('#edge-label').fill('자료 확인 후'); await page.locator('#edge-label').press('Tab');
  doc = await recovery();
  assert(doc.nodes.length === 2 && doc.edges.length === 1 && doc.edges[0].label === '자료 확인 후', 'connect two nodes and edit relationship label');
  await page.locator('[data-tool="select"]').click();
  await press('Control+a');
  await page.locator('[data-action="align-top"]').click();
  doc = await recovery(); assert(doc.nodes[0].y === doc.nodes[1].y, 'align selected elements along top edge');
  await press('Control+g');
  const beforeMove = await recovery();
  await drag(320,280,370,350);
  doc = await recovery();
  assert(doc.nodes.every(n => n.groupId) && doc.nodes[0].x !== beforeMove.nodes[0].x && doc.nodes[1].x - beforeMove.nodes[1].x === doc.nodes[0].x - beforeMove.nodes[0].x, 'group drag keeps internal positions');
  await press('Control+d'); doc = await recovery(); assert(doc.nodes.length === 4 && doc.edges.length === 2, 'duplicate group preserves internal connection');
  await press('Control+z'); doc = await recovery(); assert(doc.nodes.length === 2, 'undo duplication');
  await press('Control+Shift+z'); doc = await recovery(); assert(doc.nodes.length === 4, 'redo duplication');
  await press('Control+z');
  await press('Control+a'); await press('Control+l'); await press('Delete');
  doc = await recovery(); assert(doc.nodes.length === 2 && doc.nodes.every(n => n.locked), 'locked elements survive Delete');
  await press('Control+a'); await press('Control+l'); await press('Control+Shift+g');
  await page.locator('#board').focus();
  await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width=700; canvas.height=350;
    const ctx=canvas.getContext('2d'); ctx.fillStyle='#dbeae3'; ctx.fillRect(0,0,700,350); ctx.fillStyle='#28665a';ctx.font='32px sans-serif';ctx.fillText('ERP 화면 캡처 예시',35,100);
    const binary=atob(canvas.toDataURL('image/png').split(',')[1]); const bytes=Uint8Array.from(binary,c=>c.charCodeAt(0));
    const data=new DataTransfer(); data.items.add(new File([bytes],'screen.png',{type:'image/png'}));
    document.querySelector('#board').dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}));
  });
  doc = await recovery(); assert(doc.nodes.length === 3 && Object.keys(doc.assets).length === 1 && doc.nodes.some(n=>n.kind==='image'), 'clipboard image becomes editable element with embedded asset');
  await press('Control+d'); doc = await recovery(); assert(Object.keys(doc.assets).length === 1 && doc.nodes.filter(n=>n.kind==='image').length === 2, 'duplicated images share one embedded asset');
  await press('Control+z');
  await page.evaluate(() => { const data = new DataTransfer(); data.setData('text/plain','외부 메모 텍스트'); document.querySelector('#board').dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true})); });
  doc = await recovery(); assert(doc.nodes.some(n=>n.text==='외부 메모 텍스트'), 'external clipboard text creates text element');
  await page.locator('#document-title').fill('통합 검사 보드'); await page.locator('#document-title').press('Tab');
  const downloadPromise = page.waitForEvent('download'); await press('Control+s'); const download=await downloadPromise; await download.saveAs('output/playwright/roundtrip.agentsketch');
  doc = await recovery(); assert(doc.title==='통합 검사 보드', 'document title and file save');
  await page.reload(); await page.locator('#document-title').waitFor(); await delay(1100);
  assert(await page.locator('#document-title').inputValue()==='통합 검사 보드', 'reload restores last board');
  doc = await recovery(); assert(doc.nodes.length===4 && doc.edges.length===1 && Object.keys(doc.assets).length===1, 'recovery retains nodes connections and image');
  for (const kind of ['png','svg','pdf']) {
    await page.locator('.export-menu summary').click(); const pending=page.waitForEvent('download'); await page.locator(`[data-action="export-${kind}"]`).click(); const file=await pending; await file.saveAs(`output/playwright/export.${kind}`); checks.push(`${kind.toUpperCase()} exported through UI`);
  }
  const chooser=page.waitForEvent('filechooser'); await press('Control+o');
  if (await page.locator('.confirm-dialog').isVisible()) await page.getByRole('button',{name:'저장하지 않고 계속'}).click();
  await (await chooser).setFiles('output/playwright/roundtrip.agentsketch');
  await delay(1000);
  await page.locator('[data-tool="select"]').click(); await press('Control+a'); await page.locator('[data-action="auto-layout"]').click();
  doc = await recovery(); assert(doc.nodes.length===4 && doc.edges.length===1, 'auto layout retains all content');
  const z0 = await page.locator('#zoom-value').textContent(); await page.mouse.move(500,400); await page.mouse.wheel(0,-100); await delay(100);
  assert(await page.locator('#zoom-value').textContent()!==z0,'wheel zoom changes viewport');
  await page.locator('[data-action="fit"]').click();
  await page.screenshot({path:'output/playwright/edited.png'});
  assert(errors.length===0,`no runtime errors (${errors.length})`);
  return {checks, errors};
}
